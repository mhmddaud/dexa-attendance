/**
 * Idempotent DDL for the ATTENDANCE table.
 *
 * Oracle has no "CREATE TABLE IF NOT EXISTS", so each statement is wrapped in a
 * PL/SQL block that swallows the "already exists" error codes:
 *   ORA-00955  name is already used by an existing object (table/index/constraint)
 */
export const CREATE_ATTENDANCE_TABLE = `
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE ATTENDANCE (
      ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      USER_ID NUMBER NOT NULL,
      ATTENDANCE_DATE DATE NOT NULL,
      CHECK_IN TIMESTAMP NULL,
      CHECK_OUT TIMESTAMP NULL,
      PHOTO_CHECK_IN VARCHAR2(500) NULL,
      PHOTO_CHECK_OUT VARCHAR2(500) NULL,
      LATITUDE_CHECK_IN NUMBER(10, 7) NULL,
      LATITUDE_CHECK_OUT NUMBER(10, 7) NULL,
      LONGITUDE_CHECK_IN NUMBER(10, 7) NULL,
      LONGITUDE_CHECK_OUT NUMBER(10, 7) NULL,
      NOTE_CHECK_IN VARCHAR2(500) NULL,
      NOTE_CHECK_OUT VARCHAR2(500) NULL,
      STATUS VARCHAR2(20) DEFAULT ''PRESENT'' NOT NULL,
      CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
      UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
      CONSTRAINT UK_ATTENDANCE_USER_DATE UNIQUE (USER_ID, ATTENDANCE_DATE),
      CONSTRAINT CK_ATTENDANCE_STATUS CHECK (STATUS IN (''PRESENT'', ''LATE'', ''ABSENT''))
    )
  ';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN
      RAISE;
    END IF;
END;
`;

/**
 * Migrate existing ATTENDANCE tables by adding the longitude columns when they
 * are missing. ORA-01430 = "column being added already exists" is ignored so
 * this is safe to run on every boot.
 */
export const ADD_LONGITUDE_COLUMNS = `
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE ATTENDANCE ADD (
    LONGITUDE_CHECK_IN NUMBER(10, 7) NULL,
    LONGITUDE_CHECK_OUT NUMBER(10, 7) NULL
  )';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -1430 THEN
      RAISE;
    END IF;
END;
`;

/**
 * Rebuild the status CHECK constraint to remove 'LEAVE'. Drops the old
 * constraint (ignoring ORA-02443 "constraint does not exist") and recreates it
 * with only PRESENT/LATE/ABSENT (ignoring ORA-02264 "name already used").
 */
export const REBUILD_STATUS_CONSTRAINT = `
BEGIN
  BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE ATTENDANCE DROP CONSTRAINT CK_ATTENDANCE_STATUS';
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE != -2443 THEN RAISE; END IF;
  END;
  BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE ATTENDANCE ADD CONSTRAINT CK_ATTENDANCE_STATUS CHECK (STATUS IN (''PRESENT'', ''LATE'', ''ABSENT''))';
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE != -2264 THEN RAISE; END IF;
  END;
END;
`;
